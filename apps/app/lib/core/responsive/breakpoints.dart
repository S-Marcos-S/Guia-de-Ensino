/// Definição de pontos de interrupção (breakpoints) para layouts adaptáveis.
abstract final class Breakpoints {
  /// Limite superior para telas móveis (smartphones)
  static const double mobileMax = 720;

  /// Limite para telas médias (tablets)
  static const double tabletMax = 1100;

  /// Largura máxima recomendada para leitura e formulários
  static const double maxContentWidth = 1200;
}
